export const UI_COPY: Record<Locale, Record<UiCopyKey, string>> = {
  en,
  'zh-TW': zhTW,
}

export function translateUi(
  locale: Locale,
  key: UiCopyKey,
  params: UiCopyParams = {},
): string {
  return Object.entries(params).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    UI_COPY[locale][key],
  )
}
